function NL_dB = MarineAmbientNoise( ...
    f_kHz,B_Hz,shipping,windSpeed)
% =========================================================================
% Marine ambient-noise model:
% turbulence + shipping + wind/wave + thermal noise
%
% f is in kHz.
% windSpeed is in m/s.
% =========================================================================

f = max(f_kHz,1e-3);

s = min(max(shipping,0),1);

w = max(windSpeed,0);

Nturb_dB = ...
    17 - 30*log10(f);

Nship_dB = ...
    40 + 20*(s-0.5) ...
    + 26*log10(f) ...
    - 60*log10(f+0.03);

Nwind_dB = ...
    50 + 7.5*sqrt(w) ...
    + 20*log10(f) ...
    - 40*log10(f+0.4);

Nthermal_dB = ...
    -15 + 20*log10(f);

NtotalPSD = ...
      10^(Nturb_dB/10) ...
    + 10^(Nship_dB/10) ...
    + 10^(Nwind_dB/10) ...
    + 10^(Nthermal_dB/10);

NL_dB = ...
    10*log10(NtotalPSD) ...
    + 10*log10(max(B_Hz,1));

end
